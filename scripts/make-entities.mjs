/*
 * make-entities.mjs — `make entities`: regenerate src/js/parser/entities.js,
 * the table of HTML named character references the parser decodes.
 *
 * CommonMark only recognises references that END in a semicolon (spec §2.5),
 * so the legacy no-semicolon spellings in WHATWG's list (`&amp` without `;`)
 * are dropped. The output is committed: the app must never fetch it.
 *
 *     node scripts/make-entities.mjs [entities.json]
 *
 * With no argument the list is downloaded from the HTML Standard.
 */

import { readFile, writeFile } from "node:fs/promises";

const URL_ = "https://html.spec.whatwg.org/entities.json";
const OUT = new URL("../src/js/parser/entities.js", import.meta.url);

const source = process.argv[2]
  ? await readFile(process.argv[2], "utf8")
  : await (await fetch(URL_)).text();
const table = JSON.parse(source);

const header = (await readFile(new URL("./make-entities.mjs", import.meta.url), "utf8")).split("\n").slice(0, 15).join("\n");

// Every non-ASCII character is written as an escape, so the file is plain
// ASCII and survives any editor or diff tool.
const esc = (s) =>
  [...s]
    .map((ch) => {
      const cp = ch.codePointAt(0);
      if (cp >= 0x20 && cp < 0x7f && ch !== '"' && ch !== "\\") return ch;
      return cp > 0xffff ? `\\u{${cp.toString(16)}}` : `\\u${cp.toString(16).padStart(4, "0")}`;
    })
    .join("");

const rows = Object.keys(table)
  .filter((k) => k.endsWith(";"))
  .sort()
  .map((k) => `  ${JSON.stringify(k.slice(1, -1))}: "${esc(table[k].characters)}",`);

const body = `${header}

/*
 * entities.js — GENERATED by scripts/make-entities.mjs; do not edit.
 *
 * HTML named character references (name without & and ;) → the characters
 * they stand for. Source: ${URL_}, CC BY 4.0, (c) WHATWG.
 */

export const ENTITIES = Object.freeze({
${rows.join("\n")}
});
`;

await writeFile(OUT, body);
console.log(`Wrote ${rows.length} entities to ${OUT.pathname}`);
